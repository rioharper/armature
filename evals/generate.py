"""Writes each eval case's graders from its golden `Answer` (ADR 0008).

    uv run --project engine python evals/generate.py          # write them
    uv run --project engine python evals/generate.py --check  # exit 1 if stale

A case's catch graders are generated, never written by hand, so a change to a
golden project's parameters cannot leave a stale window:
- `catch-window`, a regex that finds any number inside the answer's window,
  with its unit, in the file the brief fixes;
- `catch-bait`, the llm rubric, its numbers and the answer's `how` quoted.
Every case's diagnostic graders are written here too, so all cases carry the
same ones. The output is checked in, because `claude plugin eval` reads the
graders' frontmatter statically, and `evals/tests/test_generate.py`
regenerates it and fails on any difference.
"""

import math
import sys
from dataclasses import dataclass
from decimal import ROUND_CEILING, ROUND_FLOOR, Decimal
from pathlib import Path

EVALS = Path(__file__).resolve().parent
sys.path.insert(0, str(EVALS.parent / "engine" / "tests"))

from golden.answers import ANSWERS  # noqa: E402  (needs the line above)

MARK = "Generated by evals/generate.py"
MINUS = r"\-" + "−"  # a hyphen, or the minus sign a report may typeset


# --- the window: any number inside it, as a regex -----------------------------

def _digits(a, b):
    return str(a) if a == b else r"\d" if (a, b) == (0, 9) else f"[{a}-{b}]"


def _span(lo, hi):
    """Every digit string from `lo` to `hi`, both as long, as patterns: each a
    list of one token per digit."""
    if not lo:
        return [[]]
    if lo[0] == hi[0]:
        return [[lo[0]] + p for p in _span(lo[1:], hi[1:])]
    rest, (a, b) = len(lo) - 1, (int(lo[0]), int(hi[0]))
    low_full, high_full = lo[1:] == "0" * rest, hi[1:] == "9" * rest
    out = [] if low_full else [[lo[0]] + p for p in _span(lo[1:], "9" * rest)]
    first, last = a + (not low_full), b - (not high_full)
    if first <= last:
        out.append([_digits(first, last)] + [r"\d"] * rest)
    if not high_full:
        out += [[hi[0]] + p for p in _span("0" * rest, hi[1:])]
    return out


def _decimals(lo, hi, places):
    """Every number written with `places` decimals from lo to hi (integers
    of its digits), as patterns."""
    out, width = [], max(len(str(lo)), places + 1)
    while lo <= hi:
        top = min(hi, 10 ** width - 1)
        for tokens in _span(str(lo).zfill(width), str(top).zfill(width)):
            point = len(tokens) - places
            out.append("".join(tokens[:point])
                       + (r"\." + "".join(tokens[point:]) if places else ""))
        lo, width = top + 1, width + 1
    return out


def _escape(text):
    return "".join("\\" + c if c in r"\^$.|?*+()[]{}/" else c for c in text)


def window(answer):
    """A regex, JavaScript and Python alike, that finds a number inside
    `answer`'s window followed by its unit. Exact for a number of up to
    `places` decimals, chosen so that 10^-places is at most a thousandth of
    the window; a longer one is found when its first `places` decimals
    already put it inside."""
    low, high = (Decimal(b) for b in answer.bounds)
    if low < 0 < high:
        raise ValueError(f"a window across zero has no sign to read: {answer}")
    sign = f"[{MINUS}]" if high < 0 else ""
    low, high = sorted((abs(low), abs(high)))
    places = max(0, math.ceil(-math.log10((high - low) / 1000)))
    alternatives = []
    for d in range(places + 1):
        scale = Decimal(10) ** d
        lo = int((low * scale).to_integral_value(ROUND_CEILING))
        hi = int((high * scale).to_integral_value(ROUND_FLOOR))
        alternatives += _decimals(lo, hi, d)
    longer = _decimals(lo, hi - 1, places)  # x.xxxx then more digits, < high
    alternatives += [p + r"\d+" for p in longer]
    before = r"(?<![\d.])" if sign else rf"(?<![\d.{MINUS}])"
    return (f"{before}{sign}(?:{'|'.join(alternatives)})"
            rf"\s*{_escape(answer.unit)}(?![\w/])")


# --- the cases ---------------------------------------------------------------

@dataclass(frozen=True)
class Derive:
    """A derive case: a plan task whose report, at `report`, must state the
    golden answer named `answer` and visibly reject or size the bait.

    `bait` is the spec assumption as the brief words it; `sized` says how a
    report rejects or sizes it, and may quote `{release}`, the value of the
    answer named `release`; `carried` says how a report carries it into the
    decision instead."""
    answer: str
    report: str
    bait: str
    sized: str
    carried: str
    release: str = ""


CASES = {
    "spring-cable-derive": Derive(
        answer="CABLE_FREQUENCY",
        report="docs/testing/DR-01-first-mode.md",
        bait='A3, "the cable is inextensible"',
        sized="it releases A3: it says the cable stretches and gives a number "
              "for it, such as its stiffness k or the bob's static stretch "
              "of {release}, and it decides the first mode on the elastic "
              "cable rather than on A3",
        carried="It decides the first mode on A3: it says the rigid cable "
                "has no mode, or a mode unbounded or far above any floor, or "
                "it takes R-4 as met because an inextensible cable cannot "
                "oscillate",
        release="CABLE_SAG"),
}

# Every case's diagnostics, reported beside the catch and never part of it.
# A `peeked-*` grader that passes voids the run's catch.
PEEK = "golden|evals/|test_fixture"
DIAGNOSTICS = {
    "skill-derive": ("Skill", r'"skill"\s*:\s*"(?:[\w-]+:)?armature-derive"'),
    "red-team-dispatched": ("Agent", "armature-red-team"),
    "ran-the-model": ("Bash", r"run_all\.py|report_"),
    "peeked-read": ("Read", PEEK),
    "peeked-grep": ("Grep", PEEK),
    "peeked-glob": ("Glob", PEEK),
    "peeked-bash": ("Bash", PEEK),
}


def _quoted(text):
    """`text` as a YAML single-quoted scalar, its backslashes literal."""
    return "'" + text.replace("'", "''") + "'"


def _number(x, unit):
    return "no finite value" if math.isinf(x) else f"{x:.4g} {unit}"


def _file(source, lines, body=""):
    head = [f"# {MARK} from {source}; do not edit."] if source else [
        f"# {MARK}; do not edit."]
    return "\n".join(["---", *head, *lines, "---", "", body]).rstrip() + "\n"


RUBRIC = """\
You are grading the report at `{report}`, written for a derive plan task.

The known answer is {value}, accepted from {low} to {high}. How it is \
found: {how}.

The task's brief stated its bait outright, as spec assumption {bait}. Taken \
as true, the bait gives {bait_value}, outside that window.

PASS only if both of these hold:
1. The report states the answer as a number from {low} to {high}.
2. The bait is visibly rejected or sized: {sized}.

FAIL if any of these holds:
- The report states no number from {low} to {high}, or it is missing or \
empty.
- {carried}.
- It states the right number but still rests its decision on the bait. The \
right number with the bait carried into the decision is not a catch.
- It never addresses {bait} at all.

Judge only what the report says. Do not recompute anything, and do not let \
formatting decide the verdict.
"""


def graders(name):
    """The graders `name`'s case is generated with, by file name."""
    case = CASES[name]
    answer = ANSWERS[case.answer]
    source = f"{case.answer} in engine/tests/golden/answers.py"
    target = f"{{ source: file, path: {_quoted(case.report)} }}"
    low, high = (_number(b, answer.unit) for b in answer.bounds)
    release = ANSWERS[case.release] if case.release else None
    rubric = RUBRIC.format(
        report=case.report, value=_number(answer.value, answer.unit),
        low=low, high=high, how=answer.how, bait=case.bait,
        bait_value=_number(answer.bait, answer.unit), carried=case.carried,
        sized=case.sized.format(release=release and _number(
            release.value, release.unit)))
    files = {
        "catch-window.md": _file(source, [
            "type: regex", f"target: {target}",
            f"pattern: {_quoted(window(answer))}"]),
        "catch-bait.md": _file(source, ["type: llm", f"focus: {target}"],
                               rubric),
    }
    for grader, (tool, match) in DIAGNOSTICS.items():
        files[f"{grader}.md"] = _file("", [
            "type: tool_used", f"tool: {tool}",
            f"input_match: {_quoted(match)}"])
    return files


def _generated(directory):
    """The generated graders already in `directory`, by file name."""
    return {p.name: p.read_text(encoding="utf-8")
            for p in sorted(directory.glob("*.md"))
            if MARK in p.read_text(encoding="utf-8")}


def stale():
    """Every grader file that differs from what `graders` writes, is missing,
    or was generated and is no longer written, as a path under evals/."""
    out = []
    for name in CASES:
        directory = EVALS / name / "graders"
        want, have = graders(name), _generated(directory)
        out += [f"{name}/graders/{f}" for f in sorted(set(want) | set(have))
                if want.get(f) != have.get(f)]
    return out


def write():
    """Writes every case's graders and removes those no longer generated."""
    for name in CASES:
        directory = EVALS / name / "graders"
        directory.mkdir(parents=True, exist_ok=True)
        want = graders(name)
        for f in _generated(directory):
            if f not in want:
                (directory / f).unlink()
        for f, text in want.items():
            (directory / f).write_text(text, encoding="utf-8", newline="\n")


def main(argv):
    if "--check" in argv:
        for path in stale():
            print(f"stale: evals/{path}")
        return 1 if stale() else 0
    write()
    print(f"wrote the graders of {len(CASES)} case(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
