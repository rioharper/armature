SEARCH_RATE = 200.0    # Hz: a mission's samples in a search
CONFIRM_RATE = 1000.0  # Hz: at the worst case's confirmation
CONTINUITY = 1e-9      # rad or m: how far one segment may start from where
                       # the one before it ended
DIFFERENCE_STEP = 1e-4  # s: the step a followed q(t) is differenced at,
    # where its rates are not given. Its acceleration is good to about 1e-8
    # relative: h² q'''' / 12 against 4 ε q / h²
END_TOL = 1e-12        # s: a last sample this close to the end is the end
FACE_TOL = 1e-12       # how far past a range's face a move may end, as a
    # share of the face's value (at least 1e-12 rad or m): a distance
    # worked to the face carries a few ulps, ~1e-16 of it, and a picometre
    # on a metre is no motion


ALONG = ("coordinate", "path")


@dataclass(frozen=True)
class Limits:
    """A move's velocity `v`, acceleration `a` and jerk `j` limits (rad/s,
    rad/s², rad/s³ on a hinge; m/s and so on on a slide), and what they
    bound, a required choice, since the two differ by √n on a diagonal:

    - `along="coordinate"`: each independent coordinate's rate and its
      derivatives. Each limit is a positive number, the same on every
      coordinate, or a mapping that gives one for every coordinate the move
      runs over.
    - `along="path"`: the magnitude of the rate and its derivatives along
      the move's straight line, as a speed limit in m/s is stated. Each
      limit is one positive number, and the coordinates share a unit."""
    v: object
    a: object
    j: object
    _: KW_ONLY
    along: str

    def __post_init__(self):
        if self.along not in ALONG:
            raise ValueError(f"limits are along one of "
                             f"{', '.join(repr(a) for a in ALONG)}; got "
                             f"{self.along!r}")
        if self.along == "path" and any(
                isinstance(getattr(self, label), Mapping)
                for label in ("v", "a", "j")):
            raise ValueError("limits along the path are one number each, "
                             "not one per coordinate")
        for label in ("v", "a", "j"):
            value = getattr(self, label)
            if isinstance(value, Mapping):
                checked = MappingProxyType(
                    {n: _positive(x, f"limit {label} on {n!r}")
                     for n, x in value.items()})
            else:
                checked = _positive(value, f"limit {label}")
            object.__setattr__(self, label, checked)

    def _over(self, names):
        """Each limit as a list over `names`, for ruckig."""
        out = []
        for label in ("v", "a", "j"):
            value = getattr(self, label)
            if not isinstance(value, Mapping):
                out.append([value] * len(names))
                continue
            missing = [n for n in names if n not in value]
            if missing:
                raise KeyError(f"limit {label} gives no value for {missing}; "
                               f"the move runs over {list(names)}")
            out.append([value[n] for n in names])
        return out


@dataclass(frozen=True)
class Duty:
    """How a mission repeats: once every `period` (s) for a `session` (s),
    idle for the rest of each period."""
    period: float
    session: float

    def __post_init__(self):
        period = _positive(self.period, "a duty's period")
        session = _positive(self.session, "a duty's session")
        if session < period:
            raise ValueError(f"a duty's session ({session} s) is at least "
                             f"one period ({period} s)")
        object.__setattr__(self, "period", period)
        object.__setattr__(self, "session", session)


@dataclass(frozen=True, eq=False)
class Move:
    """A rest-to-rest move; make one with `move`."""
    start: object
    end: object
    direction: object
    distance: float
    limits: Limits
    within: Mapping = MappingProxyType({})
    clip: bool = False

    def _profile(self, m, before):
        names = _scalar_independent(m, "a move")
        start = _posture(m, self.start, "a move's start")
        box = _envelope(m, names, self.within)
        _inside(box, start)
        if self.end is not None:
            end = _posture(m, self.end, "a move's end")
        else:
            unit = _direction(m, self.direction)
            distance = (_to_face(box, start, unit, self.distance)
                        if self.clip else self.distance)
            end = {n: start[n] + distance * unit[n] for n in names}
        end = _inside(box, end)
        if self.limits.along == "path":
            # One profile in the distance s along the line; the rates are
            # the line's unit vector times ṡ and s̈.
            span = np.array([end[n] - start[n] for n in names])
            length = float(np.linalg.norm(span))
            unit = span / length if length > 0 else span
            limits = self.limits
            duration, at = _plan([0.0], [length], [limits.v], [limits.a],
                                 [limits.j], start, end)

            def along(t):
                (s,), (sd,), (sdd,) = at(t)
                return (_clamped(box, {n: start[n] + s * u
                                       for n, u in zip(names, unit)}),
                        dict(zip(names, sd * unit)),
                        dict(zip(names, sdd * unit)))
        else:
            v, a, j = self.limits._over(names)
            duration, at = _plan([start[n] for n in names],
                                 [end[n] for n in names], v, a, j, start,
                                 end)

            def along(t):
                q, qd, qdd = at(t)
                return (_clamped(box, dict(zip(names, q))),
                        dict(zip(names, qd)),
                        dict(zip(names, qdd)))

        def sample(t):
            if t >= duration:  # ruckig lands within an ulp; the end is exact
                return dict(end), {n: 0.0 for n in names}, {
                    n: 0.0 for n in names}
            return along(t)
        return _Profile("move", duration, start, end, sample, None, False)


def _envelope(m, names, within):
    """Each of `names`' (low, high): its joint's range, unbounded without
    one, and inside `within[name]` where it gives one."""
    unknown = sorted(set(within) - set(names))
    if unknown:
        raise KeyError(f"a move's within: {unknown} not among the "
                       f"independent coordinates {list(names)}")
    out = {}
    for n in names:
        joint = m._coordinate[n][0]
        lo, hi = ((-math.inf, math.inf) if joint.range is None
                  else (float(v) for v in joint.range))
        if n in within:
            lo, hi = max(lo, within[n][0]), min(hi, within[n][1])
        out[n] = (lo, hi)
    return out


def _to_face(box, start, unit, distance):
    """`distance`, or the distance from `start` along `unit` to the first
    face of `box` it meets where that is nearer, and 0 where `start` is on
    a face it heads out of."""
    for n, u in unit.items():
        lo, hi = box[n]
        if u > 0:
            distance = min(distance, (hi - start[n]) / u)
        elif u < 0:
            distance = min(distance, (lo - start[n]) / u)
    return max(distance, 0.0)


def _inside(box, posture):
    """`posture` with each value within `FACE_TOL` past its face put on it.
    Raises `Infeasible`, naming the coordinate, where one lies further
    out."""
    out = {}
    for n, value in posture.items():
        lo, hi = box[n]
        if lo <= value <= hi:
            out[n] = value
        elif lo - _tolerance(lo) <= value < lo:
            out[n] = lo
        elif hi < value <= hi + _tolerance(hi):
            out[n] = hi
        else:
            raise Infeasible(f"a move out of the envelope along {n!r}")
    return out


def _tolerance(face):
    return FACE_TOL * max(1.0, abs(face))


def _clamped(box, q):
    """`q` inside `box`: a sample along a move whose ends are inside it
    leaves it by rounding only."""
    return {n: min(max(value, box[n][0]), box[n][1])
            for n, value in q.items()}


def _plan(start, end, v, a, j, named_start, named_end):
    """ruckig's rest-to-rest profile from `start` to `end`, phase
    synchronised so it runs a straight line: its duration, and `at(t)`,
    (q, qd, qdd) at t into it."""
    dofs = len(start)
    inp = InputParameter(dofs)
    inp.current_position, inp.target_position = start, end
    inp.max_velocity, inp.max_acceleration, inp.max_jerk = v, a, j
    inp.synchronization = Synchronization.Phase  # a straight line
    trajectory = Trajectory(dofs)
    result = Ruckig(dofs).calculate(inp, trajectory)
    if result not in (Result.Working, Result.Finished):
        raise ValueError(f"ruckig could not plan the move from {named_start} "
                         f"to {named_end}: {result.name}")
    return float(trajectory.duration), trajectory.at_time


@dataclass(frozen=True, eq=False)
class Hold:
    """A posture held at rest; make one with `hold`."""
    posture: object
    duration: float
    loads: Mapping

    def _profile(self, m, before):
        if self.posture is None:
            if before is None:
                raise ValueError("a hold with no posture holds where the "
                                 "segment before it ended, and it is first")
            posture = dict(before)
        else:
            posture = _posture(m, self.posture, "a hold's posture")
        rest = {d: 0.0 for d in _independent_dofs(m)}
        return _Profile("hold", self.duration, posture, posture,
                        lambda t: (posture, rest, rest), self.loads, True)


@dataclass(frozen=True, eq=False)
class Follow:
    """A prescribed q(t); make one with `follow`."""
    q: Callable
    duration: float
    qd: object
    qdd: object
    loads: Mapping

    def _profile(self, m, before):
        free = [n for n in m.independent if isinstance(m.home(n), Placement)]
        if free and (self.qd is None or self.qdd is None):
            raise ValueError(f"{free}: {_floating(free)}; a followed q(t) "
                             f"is differenced only over scalar coordinates, "
                             f"so give its qd and qdd")

        def posture(t):
            return _posture(m, self.q(t), "a followed q(t)")

        def sample(t):
            q = posture(t)
            if self.qd is None or self.qdd is None:
                rate, accel = _difference(posture, t, self.duration)
            qd = dict(self.qd(t)) if self.qd is not None else rate
            qdd = dict(self.qdd(t)) if self.qdd is not None else accel
            return q, qd, qdd
        return _Profile("follow", self.duration, posture(0.0),
                        posture(self.duration), sample, self.loads, False)


def move(start, end=None, direction=None, distance=None, *, limits,
         within=None, clip=False):
    """A move from `start`, rest to rest, to `end`, or along `direction` for
    `distance`, under `limits`.

    `start` and `end` are postures: a `State`, as a `Coordinates` axis gives
    one, or a mapping of independent coordinates by name, an omitted one at
    home. `direction` is a mapping of components by coordinate, or a
    sequence read in the order of `m.independent`, so a `Direction` axis's
    base-frame vector reads x, y, z as the first three; a component past the
    coordinates must be zero. Only its sense counts: it is normalised, and
    `distance` (≥ 0, as an `Interval` axis gives it) is travelled along the
    unit vector in the coordinates, rad and m alike. A move runs over scalar
    coordinates only: lock a floating body's turns so its point is three
    slides, or follow a q(t).

    The move stays inside the envelope: each coordinate's joint range, and
    `within[name]`, a (low, high), where given, as a `Coordinates` axis
    takes it. One that starts or ends outside raises `Infeasible`, naming
    the coordinate, so a search counts the point as rejected; one that ends
    within `FACE_TOL` of a face, by rounding, ends on it. With `clip`, a
    move along a direction is shortened to the first face it meets
    instead, to nothing where it starts on a face heading out."""
    if (end is None) == (direction is None):
        raise ValueError("a move goes to an end, or along a direction for a "
                         "distance; give one of the two")
    if (direction is None) != (distance is None):
        raise ValueError("a move along a direction takes a distance, and "
                         "only then")
    if clip and end is not None:
        raise ValueError("clip shortens a move along a direction; a move "
                         "to an end has no distance to clip")
    if distance is not None:
        distance = float(distance)
        if not (math.isfinite(distance) and distance >= 0):
            raise ValueError(f"a move's distance is finite and at least 0; "
                             f"got {distance}")
    if not isinstance(limits, Limits):
        raise TypeError(f"a move's limits are a Limits(v, a, j); got "
                        f"{limits!r}")
    box = {}
    for name, pair in dict(within or {}).items():
        lo, hi = (float(v) for v in pair)
        if not lo <= hi:
            raise ValueError(f"a move's within: {name!r} has its low above "
                             f"its high: ({lo}, {hi})")
        box[name] = (lo, hi)
    return Move(start, end, direction, distance, limits,
                MappingProxyType(box), bool(clip))


def hold(posture, duration, loads=None):
    """`posture` held at rest for `duration` (s) under `loads`, forces at
    named sites as `inverse` takes them. A posture of None holds where the
    segment before ended."""
    return Hold(posture, _positive(duration, "a hold's duration"),
                MappingProxyType(dict(loads or {})))


def follow(q, duration, qd=None, qdd=None, loads=None):
    """The escape hatch: `q(t)`, for t in [0, `duration`] s, a mapping of
    independent coordinates as `at()` takes them, under `loads`.

    `qd(t)` and `qdd(t)`, keyed by dof, give its rates; where one is not
    given, it is differenced from `q` at `DIFFERENCE_STEP`, centrally inside
    the segment and to second order one-sided at its ends, so `q` is never
    called outside [0, duration]. A floating body's rates are always given."""
    if not callable(q):
        raise TypeError(f"follow takes a callable q(t); got {q!r}")
    for label, fn in (("qd", qd), ("qdd", qdd)):
        if fn is not None and not callable(fn):
            raise TypeError(f"follow's {label} is a callable of t; got "
                            f"{fn!r}")
    return Follow(q, _positive(duration, "a followed q(t)'s duration"), qd,
                  qdd, MappingProxyType(dict(loads or {})))


SEGMENTS = (Move, Hold, Follow, Event)


@dataclass(frozen=True, eq=False)
class Mission:
    """A named sequence of segments, run in order, with its `duty`; a duty
    of None runs it once.

    `actuation`, when given, replaces `inverse`: it is called at each sample
    as `actuation(state, qdd, loads)`, with the `State` from `m.at`, the
    independent accelerations by dof and the segment's loads, and returns
    `{actuator: (torque, speed)}`, motor side, as `inverse`'s are, the same
    actuators at every sample. Its actuators need not be the engine's. An
    actuator may add a third number, `(torque, speed, rotor)`: the rotor's
    own inertia torque J_m·ω̇_m within its torque, which `Trace.output`
    takes out before the gear; without it, the rotor's share is zero. An
    event simulates the engine's own actuators, so a mission with one has
    no actuation."""
    name: str
    segments: tuple
    duty: Duty = None
    actuation: Callable = None

    def __post_init__(self):
        segments = tuple(self.segments)
        if not segments:
            raise ValueError(f"mission {self.name!r} has no segments")
        for s in segments:
            if not isinstance(s, SEGMENTS):
                raise TypeError(f"mission {self.name!r}: {s!r} is not a "
                                f"segment; make one with move, hold, "
                                f"follow or event")
        if self.duty is not None and not isinstance(self.duty, Duty):
            raise TypeError(f"mission {self.name!r}: its duty is a "
                            f"Duty(period, session); got {self.duty!r}")
        if self.actuation is not None and not callable(self.actuation):
            raise TypeError(f"mission {self.name!r}: actuation is a callable "
                            f"(state, qdd, loads); got {self.actuation!r}")
        object.__setattr__(self, "segments", segments)


@dataclass(frozen=True, eq=False)
class Trace:
    """A mission sampled at `rate` (Hz).

    `t` is each sample's time (s), from 0 to the mission's end, which is
    always the last sample; `segment` the index of the segment it falls in,
    a boundary sample belonging to the later one; `spans` each segment's
    (start, end) time. At an event's start and end, where the torque jumps,
    both sides are sampled at the boundary, at one time, the earlier
    segment's first, so the bus takes the jump as a step rather than a ramp
    over a sample interval.

    `q` is every coordinate by name, dependent ones included, each an array
    over the samples; a floating body's is a `Placement` of an (n, 3)
    position and an (n, 3, 3) rotation. `qd` is every dof's rate, and `qdd`
    each independent dof's acceleration, as the profile prescribes it; a
    closed chain's dependent accelerations are solved inside `inverse` and
    not kept.

    `torque` and `speed` are each actuator's, motor side: torque in N·m (N
    on a slide), speed in rad/s (m/s), so torque × speed is the joint's
    power. Through `inverse`, the joint feels `gear` × torque and the motor
    turns at `gear` × the joint's rate, so the output side is N·τ and ω/N;
    the torque includes the rotor's own inertia, J_m·ω̇ at the motor (the
    N²J_m reflected at the joint), and assumes a lossless gearbox. `rotor`
    is that share, J_m·ω̇_m = J_m·N·q̈, each actuator's, so the load across
    the gear is the rest: `output(actuator)` gives it at the output, ready
    for `electrical`. `gear` gives N for each of the compiled model's
    actuators. `residual` is each
    sample's `Inverse.residual`, the generalised force the actuators could
    not supply; under an actuation seam it is None.

    An event is sampled at each of its own timesteps, its state, q̈ and
    torques the simulation's own, with a residual of 0: its forces are the
    ones applied. `driven` says, for each actuator at each sample, whether
    its driver is on, so its flux brake can act: off where an event coasts
    or shorts it, on everywhere else. `events` reports each event as a
    `Simulated`, run at its timestep and at half of it.
    """
    mission: str
    rate: float
    t: np.ndarray
    segment: np.ndarray
    spans: tuple
    q: MappingProxyType
    qd: MappingProxyType
    qdd: MappingProxyType
    torque: MappingProxyType
    speed: MappingProxyType
    rotor: MappingProxyType
    gear: MappingProxyType
    residual: object
    method: str
    driven: MappingProxyType = None
    events: tuple = ()

    @property
    def duration(self):
        return float(self.t[-1])

    def peak(self, actuator):
        """The largest |torque| `actuator` sees at any sample."""
        return float(np.max(np.abs(self.torque[actuator])))

    def rms(self, actuator):
        """`actuator`'s RMS torque over the trace, as `rms_torque` takes it;
        at a single sample, |τ| there."""
        torque = self.torque[actuator]
        if self.duration == 0:
            return float(abs(torque[0]))
        return rms_torque(self.t, torque)

    def output(self, actuator, n=None):
        """`actuator`'s load at the output of its gear of ratio `n`, by
        default its `gear`: (τ_out, ω_out, rotor), with τ_out = N·(τ −
        rotor) and ω_out = ω/N, as `electrical(τ_out, ω_out, n, ...,
        rotor=rotor)` takes them. An actuation seam's actuator has no gear
        in the compiled model, so its `n` is given."""
        if n is None:
            if actuator not in self.gear:
                raise KeyError(f"{actuator!r} has no gear in the compiled "
                               f"model; give its ratio, output({actuator!r}, "
                               f"n=...)")
            n = self.gear[actuator]
        n = _positive(n, f"{actuator!r}'s gear ratio")
        rotor = self.rotor[actuator]
        return (_frozen(n * (self.torque[actuator] - rotor)),
                _frozen(self.speed[actuator] / n), rotor)


def trace(m, mission, rate, *, drive=None, capacitance=None, v_source=None,
          temperature=None):
    """`mission` on the compiled mechanism `m`, sampled at `rate` (Hz): a
    `Trace` of each actuator's motor torque and speed.

    An event is sampled at each of its own timesteps instead, and needs the
    `drive` its modes run on, with the bus at `capacitance` (F) and
    `v_source` (V), points in its bands as `charge` takes them, and each
    winding at `temperature[a]` (°C, a number; by default its resistance's
    T₀). Its bus starts where the segments before it left it, charged as
    `charge` would, or at `v_source` where it is first. Without events these
    are not read.

    Raises where a segment starts more than `CONTINUITY` from where the one
    before it ended, or where the mission runs longer than its duty's
    period."""
    rate = _positive(rate, "a trace's rate")
    segments = mission.segments
    actuators = _actuators(m)
    events = [i for i, s in enumerate(segments) if isinstance(s, Event)]
    if events:
        point = _event_bus(m, mission, drive, capacitance, v_source)
        temperature = dict(temperature or {})
    rows, times, which, driven, profiles = [], [], [], [], []
    starts, before, simulated, last = [0.0], None, [], len(segments) - 1
    for i, segment in enumerate(segments):
        begun = starts[-1]
        if isinstance(segment, Event):
            start = _event_start(m, mission, i, segment, before, profiles)
            if not rows or times[-1] == times[0]:  # no time has passed
                v0 = point[1]
            else:  # the bus as the segments before left it, at this start,
                   # which they were sampled up to
                v0 = float(charge(_assemble(
                    m, mission, rate, times, which, starts, profiles,
                    actuators, rows, driven), drive, capacitance=point[0],
                    v_source=point[1], temperature=temperature).v[-1])
            runs = [_simulate(m, start, segment, drive, actuators,
                              temperature, *point, v0, step)
                    for step in (segment.timestep, segment.timestep / 2)]
            end = runs[0].rows[-1][0]
            profile = _Profile("event", segment.duration,
                               _posture(m, start, "an event's start"),
                               _posture(m, end, "an event's end"), None,
                               segment.loads, False)
            profiles.append(profile)
            starts.append(begun + segment.duration)
            times += [begun + t for t in runs[0].t]
            which += [i] * len(runs[0].t)
            rows += runs[0].rows
            driven += runs[0].driven
            simulated.append(Simulated(i, *(
                _event_run(m, mission, i, segment, step, run, actuators)
                for step, run in zip((segment.timestep,
                                      segment.timestep / 2), runs))))
            before = profile.end
            continue
        profile = segment._profile(m, before)
        if before is not None:
            _continuous(mission.name, i, profile, before)
        following = segments[i + 1] if i < last else None
        if (isinstance(following, Event)
                and isinstance(following.start, After)
                and following.start.segment is segment):
            profile = _truncated(profile, following.start.fraction)
        profiles.append(profile)
        starts.append(begun + profile.duration)
        local = _grid(begun, starts[-1], rate, i == last)
        if i > 0 and isinstance(segments[i - 1], Event) and (
                not len(local) or local[0] != begun):
            local = np.insert(local, 0, begun)  # the event's end, this side
        if isinstance(following, Event):
            local = np.append(local, starts[-1])  # the event's start, this
                                                  # side
        _sample(m, mission, profile, local - begun, actuators, rows)
        times += list(local)
        which += [i] * len(local)
        driven += [None] * len(local)
        before = profile.end
    total = float(starts[-1])
    if mission.duty is not None and total > mission.duty.period:
        raise ValueError(f"mission {mission.name!r} runs {total:g} s, longer "
                         f"than its duty's period, {mission.duty.period:g} s")
    return _assemble(m, mission, rate, times, which, starts, profiles,
                     actuators, rows, driven, tuple(simulated))


def _grid(begun, ends, rate, last):
    """The multiples of 1/rate in [begun, ends), as one grid over the whole
    mission samples it. The last segment's run to the mission's end, which
    is always the last sample: a multiple within `END_TOL` of it is moved
    onto it."""
    first = max(0, math.floor(begun * rate) - 1)
    count = (math.floor(ends * rate * (1 + 1e-12)) if last
             else math.ceil(ends * rate) + 1)
    times = np.arange(first, count + 1) / rate
    keep = times >= begun
    if not last:
        return times[keep & (times < ends)]
    times = times[keep]
    if len(times) and times[-1] >= ends - END_TOL:
        times[-1] = ends
        return times
    return np.append(times, ends)


def _sample(m, mission, profile, local, actuators, rows):
    """Append to `rows` the samples of `profile` at its `local` times."""
    kept = None
    for time in local:
        if profile.constant and kept is not None:
            rows.append(kept)
            continue
        q, qd, qdd = profile.sample(min(max(float(time), 0.0),
                                        profile.duration))
        state = m.at(q=q, qd=qd)
        loads = profile.loads or {}
        if mission.actuation is not None:
            out = _seam(mission, state, qdd, loads)
            residual = None
        else:
            inv = state.inverse(qdd=qdd, loads=loads)
            out = {a: (inv.torque[a], gear * state.qd[joint],
                       inertia * gear * qdd.get(joint, 0.0))
                   for a, (joint, gear, inertia) in actuators.items()}
            residual = inv.residual
        row = (state, qdd, out, residual)
        if profile.constant:
            kept = row
        rows.append(row)


def _truncated(profile, fraction):
    """`profile` stopped at `fraction` of its duration, where an event
    takes over."""
    duration = fraction * profile.duration
    return _Profile(profile.kind, duration, profile.start,
                    profile.sample(duration)[0], profile.sample,
                    profile.loads, profile.constant)


def _event_bus(m, mission, drive, capacitance, v_source):
    """The bus point an event runs at, (C, V_s), after checking the drive
    carries every actuator."""
    if mission.actuation is not None:
        raise ValueError(f"mission {mission.name!r}: an event simulates the "
                         f"engine's own actuators, and an actuation seam "
                         f"replaces them; give the event its own mission")
    if not isinstance(drive, Drive):
        raise TypeError(f"mission {mission.name!r} has an event, whose modes "
                        f"run on drive data; give trace drive=Drive(...)")
    off = [a for a in m.actuators if a not in drive.bus.actuators]
    if off:
        raise ValueError(f"the drive's bus does not carry {off}; an event "
                         f"runs every actuator on its motor and driver, so "
                         f"add them to Bus(actuators=...)")
    return (_within("capacitance", drive.bus.capacitance, capacitance),
            _within("v_source", drive.bus.source.v, v_source))


def _event_start(m, mission, i, event, before, profiles):
    """The `State` event `i` starts from."""
    start = event.start
    if isinstance(start, After):
        segments = mission.segments
        if i > 0 and segments[i - 1] is start.segment:
            profile = profiles[-1]  # already stopped at the fraction
            q, qd, _ = profile.sample(profile.duration)
        elif i == 0 and not any(s is start.segment for s in segments):
            profile = start.segment._profile(m, None)
            q, qd, _ = profile.sample(start.fraction * profile.duration)
        else:
            raise ValueError(f"mission {mission.name!r}: event {i} starts "
                             f"after a segment that is not the one before "
                             f"it; an event takes over from the segment just "
                             f"before it, or, first, from one outside the "
                             f"mission")
        return m.at(q=q, qd=qd)
    if isinstance(start, State):
        independent = set(_independent_dofs(m))
        state = m.at(q=_posture(m, start, "an event's start"),
                     qd={d: v for d, v in start.qd.items()
                         if d in independent})
    else:
        state = m.at(q=_posture(m, start, "an event's start"))
    if before is not None:
        _continuous(mission.name, i, _Profile(
            "event", 0.0, _posture(m, state, ""), None, None, None, False),
            before)
    return state


def _event_run(m, mission, i, event, step, run, actuators):
    """A `Run` of event `i` at `step`, its trace the event's alone."""
    profile = _Profile("event", event.duration, None, None, None, None,
                       False)
    alone = _assemble(m, Mission(f"{mission.name}, event {i}", [event]),
                      1 / step, list(run.t), [0] * len(run.t),
                      [0.0, event.duration], [profile], actuators, run.rows,
                      run.driven)
    return Run(step, alone, run.v, run.contacts)


class _Profile:
    """A segment resolved on a compiled model: its `kind`, its `duration`,
    its `start` and `end` postures over the independent coordinates, and
    `sample(t)`, (q, qd, qdd) at t into it. A `constant` profile is the same
    state throughout, so its one sample stands for all."""

    def __init__(self, kind, duration, start, end, sample, loads, constant):
        self.kind, self.duration = kind, duration
        self.start, self.end, self.sample = start, end, sample
        self.loads, self.constant = loads, constant


def _seam(mission, state, qdd, loads):
    out = mission.actuation(state, MappingProxyType(dict(qdd)),
                            MappingProxyType(dict(loads)))
    try:
        rows = {a: tuple(float(x) for x in v) for a, v in dict(out).items()}
    except (TypeError, ValueError):
        rows = None
    if rows is None or any(len(v) not in (2, 3) for v in rows.values()):
        raise TypeError(f"mission {mission.name!r}: actuation returns "
                        f"{{actuator: (torque, speed)}} or (torque, speed, "
                        f"rotor); got {out!r}")
    return {a: v if len(v) == 3 else v + (0.0,) for a, v in rows.items()}


def _assemble(m, mission, rate, times, which, starts, profiles, actuators,
              rows, driven, events=()):
    names = tuple(rows[0][2])
    for k, row in enumerate(rows):
        if tuple(row[2]) != names:
            raise ValueError(f"mission {mission.name!r}: actuation gave "
                             f"{list(row[2])} at t = {times[k]:g} s, and "
                             f"{list(names)} at the start; the actuators "
                             f"are the same at every sample")
    states = [row[0] for row in rows]
    q = {}
    for name in m.coordinates:
        values = [s.q[name] for s in states]
        if isinstance(values[0], Placement):
            q[name] = Placement(
                _frozen(np.array([v.position for v in values])),
                _frozen(np.array([v.rotation for v in values])))
        else:
            q[name] = _frozen(np.array(values, dtype=float))
    qd = {d: _frozen(np.array([s.qd[d] for s in states])) for d in m.dofs}
    qdd = {d: _frozen(np.array([float(row[1].get(d, 0.0)) for row in rows]))
           for d in _independent_dofs(m)}
    torque = {a: _frozen(np.array([row[2][a][0] for row in rows]))
              for a in names}
    speed = {a: _frozen(np.array([row[2][a][1] for row in rows]))
             for a in names}
    rotor = {a: _frozen(np.array([row[2][a][2] for row in rows]))
             for a in names}
    residual = (None if mission.actuation is not None
                else _frozen(np.array([row[3] for row in rows])))
    on = {a: _frozen(np.array([True if d is None else d[a] for d in driven]))
          for a in names}
    method = (f"actuation(state, qdd, loads) at {rate:g} Hz"
              if mission.actuation is not None else
              f"m.at(q, qd), then State.inverse(qdd, loads), at {rate:g} Hz")
    if any(isinstance(s, Event) for s in mission.segments):
        method += ("; events forward-simulated under implicitfast, sampled "
                   "at each timestep")
    return Trace(mission.name, rate, _frozen(times), _frozen(which),
                 tuple((float(starts[i]), float(starts[i + 1]))
                       for i in range(len(profiles))),
                 MappingProxyType(q), MappingProxyType(qd),
                 MappingProxyType(qdd), MappingProxyType(torque),
                 MappingProxyType(speed), MappingProxyType(rotor),
                 MappingProxyType({a: g
                                   for a, (_, g, _) in actuators.items()}),
                 residual, method, MappingProxyType(on), events)


def _actuators(m):
    """Each actuator's joint, gear and rotor inertia J_m: the joint and gear
    from the compiled model, J_m from the description, since the model
    holds only the N²J_m summed on each joint."""
    model = m.model
    inertia = {a.name: float(a.rotor_inertia)
               for a in m.description.actuators}
    out = {}
    for i in range(model.nu):
        name = model.actuator(i).name
        joint = model.joint(int(model.actuator_trnid[i, 0])).name
        if joint in m.dependent and inertia[name]:
            raise ValueError(f"actuator {name!r} drives {joint!r}, which "
                             f"the loops solve; a trace keeps only the "
                             f"independent accelerations, so it cannot "
                             f"split out its rotor's share")
        out[name] = (joint, float(model.actuator_gear[i, 0]), inertia[name])
    return out


def _continuous(mission, i, profile, before):
    for name, value in profile.start.items():
        was = before[name]
        if isinstance(value, Placement):
            gap = max(float(np.max(np.abs(value.position - was.position))),
                      float(np.max(np.abs(value.rotation - was.rotation))))
        else:
            gap = abs(value - was)
        if gap > CONTINUITY:
            raise ValueError(f"mission {mission!r}: segment {i} (a "
                             f"{profile.kind}) starts with {name!r} at "
                             f"{value}, where segment {i - 1} ended at {was}; "
                             f"segments run in order, without jumps")


def _posture(m, value, label):
    """`value`, a `State` or a mapping, over the independent coordinates by
    name, an omitted one at home."""
    if isinstance(value, State):
        return {n: value.q[n] for n in m.independent}
    if not isinstance(value, Mapping):
        raise TypeError(f"{label} is a State or a mapping of independent "
                        f"coordinates; got {value!r}")
    unknown = sorted(set(value) - set(m.independent))
    if unknown:
        raise KeyError(f"{label}: {unknown} not among the independent "
                       f"coordinates {list(m.independent)}")
    return {n: (placement(value[n], n) if isinstance(m.home(n), Placement)
                else float(value[n])) if n in value else m.home(n)
            for n in m.independent}


def _direction(m, direction):
    """`direction` as a unit vector over the independent coordinates."""
    names = m.independent
    if isinstance(direction, Mapping):
        unknown = sorted(set(direction) - set(names))
        if unknown:
            raise KeyError(f"a move's direction: {unknown} not among the "
                           f"independent coordinates {list(names)}")
        vector = np.array([float(direction.get(n, 0.0)) for n in names])
    else:
        given = np.asarray(direction, dtype=float).ravel()
        if len(given) < len(names) or np.any(given[len(names):] != 0):
            raise ValueError(f"a move's direction {given.tolist()} is read "
                             f"in the order of the independent coordinates "
                             f"{list(names)}; it has a component for each, "
                             f"and none past them")
        vector = given[:len(names)]
    norm = float(np.linalg.norm(vector))
    if not (math.isfinite(norm) and norm > 0):
        raise ValueError(f"a move's direction has a length; got "
                         f"{vector.tolist()}")
    return dict(zip(names, vector / norm))


def _difference(posture, t, duration):
    """(qd, qdd) of the scalar coordinates by differencing `posture`, within
    [0, duration]."""
    h = min(DIFFERENCE_STEP, duration / 3)
    if t - h >= 0 and t + h <= duration:
        lo, mid, hi = posture(t - h), posture(t), posture(t + h)
        return ({n: (hi[n] - lo[n]) / (2 * h) for n in mid},
                {n: (hi[n] - 2 * mid[n] + lo[n]) / h ** 2 for n in mid})
    sign = 1 if t - h < 0 else -1  # forward at the start, backward at the end
    p = [posture(t + sign * k * h) for k in range(4)]
    return ({n: sign * (-3 * p[0][n] + 4 * p[1][n] - p[2][n]) / (2 * h)
             for n in p[0]},
            {n: (2 * p[0][n] - 5 * p[1][n] + 4 * p[2][n] - p[3][n]) / h ** 2
             for n in p[0]})


def _scalar_independent(m, what):
    names = m.independent
    free = [n for n in names if isinstance(m.home(n), Placement)]
    if free:
        raise ValueError(f"{free}: {_floating(free)}; {what} runs over "
                         f"scalar coordinates. Lock its turns so its point "
                         f"is three slides, or follow a q(t)")
    if not names:
        raise ValueError(f"{what} needs an independent coordinate to run "
                         f"over; this mechanism has none")
    return names


def _floating(names):
    return "a floating body" if len(names) == 1 else "floating bodies"


def _independent_dofs(m):
    return tuple(d for d in m.dofs if d not in m.dependent)


def _frozen(array):
    array = np.asarray(array)
    array.flags.writeable = False
    return array
