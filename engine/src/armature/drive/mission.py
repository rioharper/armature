"""Missions: what a mechanism is asked to do, sampled into each actuator's
motor torque and speed (ADR 0006).

A mission is a named sequence of segments, run in order, and a duty cycle:

    Mission("take", [move(home, end=far, limits=Limits(v=1.0, a=4.0, j=40.0)),
                     hold(far, 60.0, loads={"tip": (0, -20, 0)}),
                     move(far, end=home, limits=...)],
            duty=Duty(period=360.0, session=4 * 3600.0))

Every profile is over the description's independent coordinates, the ones
`at()` takes, keyed by name; a closed chain's dependent ones are solved at
each sample, as `at()` always solves them. A **move** goes from `start` to
`end`, or from `start` along `direction` for `distance`, rest to rest,
generated by ruckig under velocity, acceleration and jerk limits on each
coordinate. Its phases are synchronised, so it travels a straight line in
the coordinates. A **hold** keeps a posture for a duration under loads. A
**followed** q(t) is the escape hatch, for a motion that is neither: a
project's own collapse, a prescribed swing.

`trace(m, mission, rate)` samples it at `rate`: `SEARCH_RATE` (200 Hz) in a
search, `CONFIRM_RATE` (1 kHz) for the confirmation. At each sample
`m.at(q, qd)` then `inverse(qdd, loads)` gives every actuator's motor torque,
and its speed is its gear times its joint's rate. A mission that gives an
`actuation(state, qdd, loads)` is traced through it in place of `inverse`:
the seam for a mechanism whose allocation is not the engine's least
squares, such as a cable robot's positive tensions, since the engine's
`actuator` drives joints only.

Segments run without jumps: each starts where the one before it ended, or
the trace raises, naming both. An event, forward-simulated from a state
(#87), will be a segment of its own kind; `trace` asks each segment for its
profile, and that is where an event's simulation slots in.
"""

import math
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from types import MappingProxyType

import numpy as np
from ruckig import InputParameter, Result, Ruckig, Synchronization, Trajectory

from ..state import Placement, State, placement

SEARCH_RATE = 200.0    # Hz: a mission's samples in a search
CONFIRM_RATE = 1000.0  # Hz: at the worst case's confirmation
CONTINUITY = 1e-9      # rad or m: how far one segment may start from where
                       # the one before it ended
DIFFERENCE_STEP = 1e-4  # s: the step a followed q(t) is differenced at,
    # where its rates are not given. Its acceleration is good to about 1e-8
    # relative: h² q'''' / 12 against 4 ε q / h²
END_TOL = 1e-12        # s: a last sample this close to the end is the end


@dataclass(frozen=True)
class Limits:
    """A move's velocity `v`, acceleration `a` and jerk `j` limits, on each
    independent coordinate's rate and its derivatives (rad/s, rad/s²,
    rad/s³ on a hinge; m/s and so on on a slide). Each is a positive number,
    the same on every coordinate, or a mapping that gives one for every
    coordinate the move runs over."""
    v: object
    a: object
    j: object

    def __post_init__(self):
        for label in ("v", "a", "j"):
            value = getattr(self, label)
            if isinstance(value, Mapping):
                checked = MappingProxyType(
                    {n: _positive(x, f"limit {label} on {n!r}")
                     for n, x in value.items()})
            else:
                checked = _positive(value, f"limit {label}")
            object.__setattr__(self, label, checked)

    def _over(self, names):
        """Each limit as a list over `names`, for ruckig."""
        out = []
        for label in ("v", "a", "j"):
            value = getattr(self, label)
            if not isinstance(value, Mapping):
                out.append([value] * len(names))
                continue
            missing = [n for n in names if n not in value]
            if missing:
                raise KeyError(f"limit {label} gives no value for {missing}; "
                               f"the move runs over {list(names)}")
            out.append([value[n] for n in names])
        return out


@dataclass(frozen=True)
class Duty:
    """How a mission repeats: once every `period` (s) for a `session` (s),
    idle for the rest of each period."""
    period: float
    session: float

    def __post_init__(self):
        period = _positive(self.period, "a duty's period")
        session = _positive(self.session, "a duty's session")
        if session < period:
            raise ValueError(f"a duty's session ({session} s) is at least "
                             f"one period ({period} s)")
        object.__setattr__(self, "period", period)
        object.__setattr__(self, "session", session)


@dataclass(frozen=True, eq=False)
class Move:
    """A rest-to-rest move; make one with `move`."""
    start: object
    end: object
    direction: object
    distance: float
    limits: Limits

    def _profile(self, m, before):
        names = _scalar_independent(m, "a move")
        start = _posture(m, self.start, "a move's start")
        if self.end is not None:
            end = _posture(m, self.end, "a move's end")
        else:
            unit = _direction(m, self.direction)
            end = {n: start[n] + self.distance * unit[n] for n in names}
        v, a, j = self.limits._over(names)
        dofs = len(names)
        inp = InputParameter(dofs)
        inp.current_position = [start[n] for n in names]
        inp.target_position = [end[n] for n in names]
        inp.max_velocity, inp.max_acceleration, inp.max_jerk = v, a, j
        inp.synchronization = Synchronization.Phase  # a straight line
        trajectory = Trajectory(dofs)
        result = Ruckig(dofs).calculate(inp, trajectory)
        if result not in (Result.Working, Result.Finished):
            raise ValueError(f"ruckig could not plan the move from {start} "
                             f"to {end}: {result.name}")
        duration = float(trajectory.duration)

        def sample(t):
            if t >= duration:  # ruckig lands within an ulp; the end is exact
                return dict(end), {n: 0.0 for n in names}, {
                    n: 0.0 for n in names}
            q, qd, qdd = trajectory.at_time(t)
            return (dict(zip(names, q)), dict(zip(names, qd)),
                    dict(zip(names, qdd)))
        return _Profile("move", duration, start, end, sample, None, False)


@dataclass(frozen=True, eq=False)
class Hold:
    """A posture held at rest; make one with `hold`."""
    posture: object
    duration: float
    loads: Mapping

    def _profile(self, m, before):
        if self.posture is None:
            if before is None:
                raise ValueError("a hold with no posture holds where the "
                                 "segment before it ended, and it is first")
            posture = dict(before)
        else:
            posture = _posture(m, self.posture, "a hold's posture")
        rest = {d: 0.0 for d in _independent_dofs(m)}
        return _Profile("hold", self.duration, posture, posture,
                        lambda t: (posture, rest, rest), self.loads, True)


@dataclass(frozen=True, eq=False)
class Follow:
    """A prescribed q(t); make one with `follow`."""
    q: Callable
    duration: float
    qd: object
    qdd: object
    loads: Mapping

    def _profile(self, m, before):
        free = [n for n in m.independent if isinstance(m.home(n), Placement)]
        if free and (self.qd is None or self.qdd is None):
            raise ValueError(f"{free}: {_floating(free)}; a followed q(t) "
                             f"is differenced only over scalar coordinates, "
                             f"so give its qd and qdd")

        def posture(t):
            return _posture(m, self.q(t), "a followed q(t)")

        def sample(t):
            q = posture(t)
            if self.qd is None or self.qdd is None:
                rate, accel = _difference(posture, t, self.duration)
            qd = dict(self.qd(t)) if self.qd is not None else rate
            qdd = dict(self.qdd(t)) if self.qdd is not None else accel
            return q, qd, qdd
        return _Profile("follow", self.duration, posture(0.0),
                        posture(self.duration), sample, self.loads, False)


def move(start, end=None, direction=None, distance=None, *, limits):
    """A move from `start`, rest to rest, to `end`, or along `direction` for
    `distance`, under `limits`.

    `start` and `end` are postures: a `State`, as a `Coordinates` axis gives
    one, or a mapping of independent coordinates by name, an omitted one at
    home. `direction` is a mapping of components by coordinate, or a
    sequence read in the order of `m.independent`, so a `Direction` axis's
    base-frame vector reads x, y, z as the first three; a component past the
    coordinates must be zero. Only its sense counts: it is normalised, and
    `distance` (≥ 0, as an `Interval` axis gives it) is travelled along the
    unit vector in the coordinates, rad and m alike. A move runs over scalar
    coordinates only: lock a floating body's turns so its point is three
    slides, or follow a q(t)."""
    if (end is None) == (direction is None):
        raise ValueError("a move goes to an end, or along a direction for a "
                         "distance; give one of the two")
    if (direction is None) != (distance is None):
        raise ValueError("a move along a direction takes a distance, and "
                         "only then")
    if distance is not None:
        distance = float(distance)
        if not (math.isfinite(distance) and distance >= 0):
            raise ValueError(f"a move's distance is finite and at least 0; "
                             f"got {distance}")
    if not isinstance(limits, Limits):
        raise TypeError(f"a move's limits are a Limits(v, a, j); got "
                        f"{limits!r}")
    return Move(start, end, direction, distance, limits)


def hold(posture, duration, loads=None):
    """`posture` held at rest for `duration` (s) under `loads`, forces at
    named sites as `inverse` takes them. A posture of None holds where the
    segment before ended."""
    return Hold(posture, _positive(duration, "a hold's duration"),
                MappingProxyType(dict(loads or {})))


def follow(q, duration, qd=None, qdd=None, loads=None):
    """The escape hatch: `q(t)`, for t in [0, `duration`] s, a mapping of
    independent coordinates as `at()` takes them, under `loads`.

    `qd(t)` and `qdd(t)`, keyed by dof, give its rates; where one is not
    given, it is differenced from `q` at `DIFFERENCE_STEP`, centrally inside
    the segment and to second order one-sided at its ends, so `q` is never
    called outside [0, duration]. A floating body's rates are always given."""
    if not callable(q):
        raise TypeError(f"follow takes a callable q(t); got {q!r}")
    for label, fn in (("qd", qd), ("qdd", qdd)):
        if fn is not None and not callable(fn):
            raise TypeError(f"follow's {label} is a callable of t; got "
                            f"{fn!r}")
    return Follow(q, _positive(duration, "a followed q(t)'s duration"), qd,
                  qdd, MappingProxyType(dict(loads or {})))


SEGMENTS = (Move, Hold, Follow)


@dataclass(frozen=True, eq=False)
class Mission:
    """A named sequence of segments, run in order, with its `duty`; a duty
    of None runs it once.

    `actuation`, when given, replaces `inverse`: it is called at each sample
    as `actuation(state, qdd, loads)`, with the `State` from `m.at`, the
    independent accelerations by dof and the segment's loads, and returns
    `{actuator: (torque, speed)}`, motor side, as `inverse`'s are, the same
    actuators at every sample. Its actuators need not be the engine's."""
    name: str
    segments: tuple
    duty: Duty = None
    actuation: Callable = None

    def __post_init__(self):
        segments = tuple(self.segments)
        if not segments:
            raise ValueError(f"mission {self.name!r} has no segments")
        for s in segments:
            if not isinstance(s, SEGMENTS):
                raise TypeError(f"mission {self.name!r}: {s!r} is not a "
                                f"segment; make one with move, hold or "
                                f"follow")
        if self.duty is not None and not isinstance(self.duty, Duty):
            raise TypeError(f"mission {self.name!r}: its duty is a "
                            f"Duty(period, session); got {self.duty!r}")
        if self.actuation is not None and not callable(self.actuation):
            raise TypeError(f"mission {self.name!r}: actuation is a callable "
                            f"(state, qdd, loads); got {self.actuation!r}")
        object.__setattr__(self, "segments", segments)


@dataclass(frozen=True, eq=False)
class Trace:
    """A mission sampled at `rate` (Hz).

    `t` is each sample's time (s), from 0 to the mission's end, which is
    always the last sample; `segment` the index of the segment it falls in,
    a boundary sample belonging to the later one; `spans` each segment's
    (start, end) time.

    `q` is every coordinate by name, dependent ones included, each an array
    over the samples; a floating body's is a `Placement` of an (n, 3)
    position and an (n, 3, 3) rotation. `qd` is every dof's rate, and `qdd`
    each independent dof's acceleration, as the profile prescribes it; a
    closed chain's dependent accelerations are solved inside `inverse` and
    not kept.

    `torque` and `speed` are each actuator's, motor side: torque in N·m (N
    on a slide), speed in rad/s (m/s), so torque × speed is the joint's
    power. Through `inverse`, the joint feels `gear` × torque and the motor
    turns at `gear` × the joint's rate, so the output side is N·τ and ω/N;
    the torque includes the rotor's own inertia, J_m·ω̇ at the motor (the
    N²J_m reflected at the joint), and assumes a lossless gearbox. `gear`
    gives N for each of the compiled model's actuators. `residual` is each
    sample's `Inverse.residual`, the generalised force the actuators could
    not supply; under an actuation seam it is None.
    """
    mission: str
    rate: float
    t: np.ndarray
    segment: np.ndarray
    spans: tuple
    q: MappingProxyType
    qd: MappingProxyType
    qdd: MappingProxyType
    torque: MappingProxyType
    speed: MappingProxyType
    gear: MappingProxyType
    residual: object
    method: str

    @property
    def duration(self):
        return float(self.t[-1])

    def peak(self, actuator):
        """The largest |torque| `actuator` sees at any sample."""
        return float(np.max(np.abs(self.torque[actuator])))

    def rms(self, actuator):
        """`actuator`'s RMS torque over the trace, √(∫τ² dt / T), by the
        trapezoid rule over its samples; at a single sample, |τ| there."""
        torque = self.torque[actuator]
        if self.duration == 0:
            return float(abs(torque[0]))
        return float(math.sqrt(np.trapezoid(torque ** 2, self.t)
                               / self.duration))


def trace(m, mission, rate):
    """`mission` on the compiled mechanism `m`, sampled at `rate` (Hz): a
    `Trace` of each actuator's motor torque and speed.

    Raises where a segment starts more than `CONTINUITY` from where the one
    before it ended, or where the mission runs longer than its duty's
    period."""
    rate = _positive(rate, "a trace's rate")
    profiles, before = [], None
    for i, segment in enumerate(mission.segments):
        profile = segment._profile(m, before)
        if before is not None:
            _continuous(mission.name, i, profile, before)
        profiles.append(profile)
        before = profile.end
    starts = np.cumsum([0.0] + [p.duration for p in profiles])
    total = float(starts[-1])
    if mission.duty is not None and total > mission.duty.period:
        raise ValueError(f"mission {mission.name!r} runs {total:g} s, longer "
                         f"than its duty's period, {mission.duty.period:g} s")
    times = _times(total, rate)
    which = np.minimum(np.searchsorted(starts, times, side="right") - 1,
                       len(profiles) - 1)

    actuators = _actuators(m)
    rows, kept = [], {}
    for time, i in zip(times, which):
        profile = profiles[i]
        local = min(max(time - starts[i], 0.0), profile.duration)
        if profile.constant and i in kept:
            rows.append(kept[i])
            continue
        q, qd, qdd = profile.sample(local)
        state = m.at(q=q, qd=qd)
        loads = profile.loads or {}
        if mission.actuation is not None:
            out = _seam(mission, state, qdd, loads)
            residual = None
        else:
            inv = state.inverse(qdd=qdd, loads=loads)
            out = {a: (inv.torque[a], gear * state.qd[joint])
                   for a, (joint, gear) in actuators.items()}
            residual = inv.residual
        row = (state, qdd, out, residual)
        if profile.constant:
            kept[i] = row
        rows.append(row)
    return _assemble(m, mission, rate, times, which, starts, profiles,
                     actuators, rows)


class _Profile:
    """A segment resolved on a compiled model: its `kind`, its `duration`,
    its `start` and `end` postures over the independent coordinates, and
    `sample(t)`, (q, qd, qdd) at t into it. A `constant` profile is the same
    state throughout, so its one sample stands for all."""

    def __init__(self, kind, duration, start, end, sample, loads, constant):
        self.kind, self.duration = kind, duration
        self.start, self.end, self.sample = start, end, sample
        self.loads, self.constant = loads, constant


def _times(total, rate):
    """Every multiple of 1/rate up to `total`, and `total` itself."""
    count = math.floor(total * rate * (1 + 1e-12))
    times = np.arange(count + 1) / rate
    if times[-1] < total - END_TOL:
        times = np.append(times, total)
    else:
        times[-1] = total
    return times


def _seam(mission, state, qdd, loads):
    out = mission.actuation(state, MappingProxyType(dict(qdd)),
                            MappingProxyType(dict(loads)))
    try:
        return {a: (float(t), float(w)) for a, (t, w) in dict(out).items()}
    except (TypeError, ValueError):
        raise TypeError(f"mission {mission.name!r}: actuation returns "
                        f"{{actuator: (torque, speed)}}; got {out!r}"
                        ) from None


def _assemble(m, mission, rate, times, which, starts, profiles, actuators,
              rows):
    names = tuple(rows[0][2])
    for k, row in enumerate(rows):
        if tuple(row[2]) != names:
            raise ValueError(f"mission {mission.name!r}: actuation gave "
                             f"{list(row[2])} at t = {times[k]:g} s, and "
                             f"{list(names)} at the start; the actuators "
                             f"are the same at every sample")
    states = [row[0] for row in rows]
    q = {}
    for name in m.coordinates:
        values = [s.q[name] for s in states]
        if isinstance(values[0], Placement):
            q[name] = Placement(
                _frozen(np.array([v.position for v in values])),
                _frozen(np.array([v.rotation for v in values])))
        else:
            q[name] = _frozen(np.array(values, dtype=float))
    qd = {d: _frozen(np.array([s.qd[d] for s in states])) for d in m.dofs}
    qdd = {d: _frozen(np.array([float(row[1].get(d, 0.0)) for row in rows]))
           for d in _independent_dofs(m)}
    torque = {a: _frozen(np.array([row[2][a][0] for row in rows]))
              for a in names}
    speed = {a: _frozen(np.array([row[2][a][1] for row in rows]))
             for a in names}
    residual = (None if mission.actuation is not None
                else _frozen(np.array([row[3] for row in rows])))
    method = (f"actuation(state, qdd, loads) at {rate:g} Hz"
              if mission.actuation is not None else
              f"m.at(q, qd), then State.inverse(qdd, loads), at {rate:g} Hz")
    return Trace(mission.name, rate, _frozen(times), _frozen(which),
                 tuple((float(starts[i]), float(starts[i + 1]))
                       for i in range(len(profiles))),
                 MappingProxyType(q), MappingProxyType(qd),
                 MappingProxyType(qdd), MappingProxyType(torque),
                 MappingProxyType(speed),
                 MappingProxyType({a: g for a, (_, g) in actuators.items()}),
                 residual, method)


def _actuators(m):
    """Each actuator's joint and gear, from the compiled model."""
    model = m.model
    return {model.actuator(i).name: (
        model.joint(int(model.actuator_trnid[i, 0])).name,
        float(model.actuator_gear[i, 0])) for i in range(model.nu)}


def _continuous(mission, i, profile, before):
    for name, value in profile.start.items():
        was = before[name]
        if isinstance(value, Placement):
            gap = max(float(np.max(np.abs(value.position - was.position))),
                      float(np.max(np.abs(value.rotation - was.rotation))))
        else:
            gap = abs(value - was)
        if gap > CONTINUITY:
            raise ValueError(f"mission {mission!r}: segment {i} (a "
                             f"{profile.kind}) starts with {name!r} at "
                             f"{value}, where segment {i - 1} ended at {was}; "
                             f"segments run in order, without jumps")


def _posture(m, value, label):
    """`value`, a `State` or a mapping, over the independent coordinates by
    name, an omitted one at home."""
    if isinstance(value, State):
        return {n: value.q[n] for n in m.independent}
    if not isinstance(value, Mapping):
        raise TypeError(f"{label} is a State or a mapping of independent "
                        f"coordinates; got {value!r}")
    unknown = sorted(set(value) - set(m.independent))
    if unknown:
        raise KeyError(f"{label}: {unknown} not among the independent "
                       f"coordinates {list(m.independent)}")
    return {n: (placement(value[n], n) if isinstance(m.home(n), Placement)
                else float(value[n])) if n in value else m.home(n)
            for n in m.independent}


def _direction(m, direction):
    """`direction` as a unit vector over the independent coordinates."""
    names = m.independent
    if isinstance(direction, Mapping):
        unknown = sorted(set(direction) - set(names))
        if unknown:
            raise KeyError(f"a move's direction: {unknown} not among the "
                           f"independent coordinates {list(names)}")
        vector = np.array([float(direction.get(n, 0.0)) for n in names])
    else:
        given = np.asarray(direction, dtype=float).ravel()
        if len(given) < len(names) or np.any(given[len(names):] != 0):
            raise ValueError(f"a move's direction {given.tolist()} is read "
                             f"in the order of the independent coordinates "
                             f"{list(names)}; it has a component for each, "
                             f"and none past them")
        vector = given[:len(names)]
    norm = float(np.linalg.norm(vector))
    if not (math.isfinite(norm) and norm > 0):
        raise ValueError(f"a move's direction has a length; got "
                         f"{vector.tolist()}")
    return dict(zip(names, vector / norm))


def _difference(posture, t, duration):
    """(qd, qdd) of the scalar coordinates by differencing `posture`, within
    [0, duration]."""
    h = min(DIFFERENCE_STEP, duration / 3)
    if t - h >= 0 and t + h <= duration:
        lo, mid, hi = posture(t - h), posture(t), posture(t + h)
        return ({n: (hi[n] - lo[n]) / (2 * h) for n in mid},
                {n: (hi[n] - 2 * mid[n] + lo[n]) / h ** 2 for n in mid})
    sign = 1 if t - h < 0 else -1  # forward at the start, backward at the end
    p = [posture(t + sign * k * h) for k in range(4)]
    return ({n: sign * (-3 * p[0][n] + 4 * p[1][n] - p[2][n]) / (2 * h)
             for n in p[0]},
            {n: (2 * p[0][n] - 5 * p[1][n] + 4 * p[2][n] - p[3][n]) / h ** 2
             for n in p[0]})


def _scalar_independent(m, what):
    names = m.independent
    free = [n for n in names if isinstance(m.home(n), Placement)]
    if free:
        raise ValueError(f"{free}: {_floating(free)}; {what} runs over "
                         f"scalar coordinates. Lock its turns so its point "
                         f"is three slides, or follow a q(t)")
    if not names:
        raise ValueError(f"{what} needs an independent coordinate to run "
                         f"over; this mechanism has none")
    return names


def _floating(names):
    return "a floating body" if len(names) == 1 else "floating bodies"


def _independent_dofs(m):
    return tuple(d for d in m.dofs if d not in m.dependent)


def _positive(value, label):
    value = float(value)
    if not (math.isfinite(value) and value > 0):
        raise ValueError(f"{label} is a positive number; got {value}")
    return value


def _frozen(array):
    array = np.asarray(array)
    array.flags.writeable = False
    return array
